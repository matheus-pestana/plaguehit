# 2. FUNÇÃO GRAD-CAM COM SUPORTE AUTOMÁTICO A CAMADAS E RESOLUÇÃO
# ==============================================================================
def analisar_imagem_com_mapa(img_path, modelo_treinado, lista_classes):
  img_original = cv2.imread(img_path)
  if img_original is None:
    print(f'❌ Erro ao ler a imagem: {img_path}')
    return

  img_original = cv2.cvtColor(img_original, cv2.COLOR_BGR2RGB)

  # Redimensiona para o tamanho exato que o modelo espera (150, 150)
  img_redimensionada = cv2.resize(img_original, (TARGET_W, TARGET_H))
  raio_x = np.expand_dims(img_redimensionada, axis=0) / 255.0

  # Localiza dinamicamente a última camada convolucional da rede
  ultima_camada_conv = None
  for layer in reversed(modelo_treinado.layers):
    if (
        'conv' in layer.name.lower()
        or isinstance(layer, tf.keras.layers.Conv2D)
        or 'Conv_1' in layer.name
    ):
      ultima_camada_conv = layer.name
      break

  if not ultima_camada_conv:
    ultima_camada_conv = 'Conv_1'

  grad_model = Model(
      inputs=[modelo_treinado.inputs],
      outputs=[
          modelo_treinado.get_layer(ultima_camada_conv).output,
          modelo_treinado.output,
      ],
  )

  with tf.GradientTape() as tape:
    conv_outputs, predictions = grad_model(raio_x)
    classe_predita_idx = np.argmax(predictions[0])
    perda = predictions[0][classe_predita_idx]

  grads = tape.gradient(perda, conv_outputs)[0]
  cam = np.dot(conv_outputs[0], tf.reduce_mean(grads, axis=(0, 1)))

  # Redimensiona o mapa de calor de volta ao tamanho original da folha
  cam = cv2.resize(cam, (img_original.shape[1], img_original.shape[0]))
  cam = np.maximum(cam, 0)

  mapa_calor = (cam - cam.min()) / (cam.max() - cam.min() + 1e-10)
  mapa_calor = np.uint8(255 * mapa_calor)
  mapa_calor = cv2.applyColorMap(mapa_calor, cv2.COLORMAP_JET)

  imagem_final = cv2.addWeighted(img_original, 0.6, mapa_calor, 0.4, 0)

  nome_classe = lista_classes[classe_predita_idx]
  confianca = float(predictions[0][classe_predita_idx]) * 100

  plt.figure(figsize=(12, 6))
  plt.subplot(1, 2, 1)
  plt.title('Imagem Original')
  plt.imshow(img_original)
  plt.axis('off')

  plt.subplot(1, 2, 2)
  plt.title(f'Diagnóstico: {nome_classe} ({confianca:.2f}%)')
  plt.imshow(imagem_final)
  plt.axis('off')
  plt.show()


